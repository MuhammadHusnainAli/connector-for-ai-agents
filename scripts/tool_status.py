#!/usr/bin/env python3
"""Write the two working lists that track tool-pack coverage.

    python scripts/tool_status.py

``tools-completed.md`` lists every connector that has a pack of its own;
``tools-remaining.md`` lists the ones still running on the default tools only:
the raw ``get_from_api`` / ``post_to_api`` / ``put_to_api`` / ``patch_api`` /
``delete_from_api`` requests, plus ``check_connection`` where the catalogue
entry declares a verification endpoint. Run it after adding a pack.
"""

from __future__ import annotations

import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO_ROOT / "src"))

from connector_manager import ConnectorManager  # noqa: E402
from connector_manager.tools import ToolRegistry  # noqa: E402

COMPLETED = REPO_ROOT / "tools-completed.md"
REMAINING = REPO_ROOT / "tools-remaining.md"

#: Tools every connector carries whether or not it has a pack.
DEFAULT_TOOLS = frozenset({
    "get_from_api", "post_to_api", "put_to_api", "patch_api", "delete_from_api",
    "list_server_tools", "call_server_tool",
})

#: Connectors someone looked at and could not write a pack for, and why. Kept
#: here so the next pass does not rediscover the same wall.
BLOCKED = {
    "browserhub": (
        "The Browserhub API is offline: every request to `api.browserhub.io/v1/...` and to the "
        "developer reference at `developer.browserhub.io` answers HTTP 503 \"This service has been "
        "suspended by its owner\" (checked 2026-10-08). Only 2023-2025 Wayback copies of the docs "
        "remain, so a pack would describe endpoints that no longer answer. If it returns, write the "
        "pack from /scrapers, /runs and /accounts and add `/scrapers` as the verification endpoint."
    ),
    "cal-com-v1": (
        "Cal.com has decommissioned API v1: `GET https://api.cal.com/v1/me` and every other v1 route "
        "answer HTTP 410 Gone with \"API v1 has been decommissioned. Please migrate to API v2\" "
        "(checked 2026-10-25). `cal-com-v2` and `cal-com-oauth` carry the v2 pack."
    ),
    "valley": (
        "The documented Valley Public API (`/public/v1/...`) accepts only the `x-api-key` header; "
        "it answers a Bearer token with \"Missing API key\". This connector signs in with email and "
        "password for a Bearer token, and the API that token opens is not published. "
        "`valley-api-key` has the full pack."
    ),
    "vantage-apparel": (
        "PromoStandards SOAP: every call carries the id and password inside the XML envelope. "
        "A tool's raw `content` is not interpolated against the connection, and arguments are not "
        "XML-escaped, so a pack would have to take the credentials as arguments. Needs executor "
        "support for a SOAP/XML body first."
    ),
}


def main() -> int:
    manager = ConnectorManager()
    tools = ToolRegistry()

    done: list[tuple[str, str, str, str, int]] = []
    left: list[tuple[str, str, str, str, int, str]] = []
    for connector in sorted(manager.registry, key=lambda c: c.id):
        pack = tools.pack(connector.id)
        names = [t.name for t in manager.list_tools(connector.id)]
        auth = connector.auth_mode.value
        if pack:
            own = len([n for n in names if n not in DEFAULT_TOOLS])
            source = "spec" if pack.generated else "authored"
            done.append((connector.id, connector.display_name, auth, source, own))
        else:
            has = "verification" if "check_connection" in names else "raw"
            left.append((
                connector.id, connector.display_name, auth, has, len(names),
                ", ".join(connector.categories or []),
            ))

    total = len(done) + len(left)
    authored = [row for row in done if row[3] == "authored"]
    spec = [row for row in done if row[3] == "spec"]
    lines = [
        "# Tools completed",
        "",
        "Generated by `python scripts/tool_status.py`.",
        "",
        "Connectors that have a tool pack of their own: real, named operations rather than",
        "only the raw `get_from_api` / `post_to_api` / `put_to_api` / `patch_api` /",
        "`delete_from_api` request tools. The counterpart list is",
        "[tools-remaining.md](tools-remaining.md).",
        "",
        f"**{len(done):,} of {total:,} connectors** — {len(authored):,} hand-authored "
        f"({sum(row[4] for row in authored):,} tools), {len(spec):,} generated from an OpenAPI spec "
        f"({sum(row[4] for row in spec):,} tools).",
        "",
        "`Tools` counts the pack's own tools; the raw request tools every connector also",
        "carries are left out. `spec` packs cover a slice of the API and are candidates for",
        "a full replacement.",
        "",
        "| Connector | Provider | Auth | Source | Tools |",
        "|---|---|---|---|---:|",
    ]
    lines += [f"| `{cid}` | {name} | {auth} | {source} | {count} |" for cid, name, auth, source, count in done]
    COMPLETED.write_text("\n".join(lines) + "\n", encoding="utf-8")

    raw = [row for row in left if row[3] == "raw"]
    verification = [row for row in left if row[3] == "verification"]
    lines = [
        "# Tools remaining",
        "",
        "Generated by `python scripts/tool_status.py`.",
        "",
        "Connectors still running on the default tools only: the five raw request tools",
        "(`get_from_api`, `post_to_api`, `put_to_api`, `patch_api`, `delete_from_api`), plus",
        "`check_connection` where the catalogue entry declares a verification endpoint.",
        "Each one needs a pack under `src/connector_manager/data/tools/<auth-mode>/`. Finished",
        "connectors are in [tools-completed.md](tools-completed.md).",
        "",
        f"**{len(left):,} of {total:,} connectors** — {len(raw):,} raw only, "
        f"{len(verification):,} raw plus `check_connection`.",
        "",
    ]
    blocked = [(cid, why) for cid, why in BLOCKED.items() if any(row[0] == cid for row in left)]
    if blocked:
        lines += ["## Looked at and blocked", ""]
        lines += [f"- `{cid}` — {why}" for cid, why in blocked]
        lines += [""]
    lines += [
        "## All remaining connectors",
        "",
        "| Connector | Provider | Auth | Has | Default tools | Categories |",
        "|---|---|---|---|---:|---|",
    ]
    lines += [
        f"| `{cid}` | {name} | {auth} | {has} | {count} | {categories} |"
        for cid, name, auth, has, count, categories in left
    ]
    REMAINING.write_text("\n".join(lines) + "\n", encoding="utf-8")

    print(f"wrote {COMPLETED.name}: {len(done):,} connectors with a pack")
    print(f"wrote {REMAINING.name}: {len(left):,} connectors on the default tools")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
